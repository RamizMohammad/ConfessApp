def fonts(res: Path, check: bool) -> tuple[str, list[str]]:
    faces, problems = [], []
    try:
        from fontTools.ttLib import TTFont  # type: ignore
        import brotli  # type: ignore  # noqa: F401
        can = True
    except ImportError:
        can = False
    for ttf in sorted((res / "font").glob("*.ttf")):
        spec = FONT_FILES.get(ttf.stem)
        if not spec:
            problems.append(f"font {ttf.name} has no web mapping — add it to FONT_FILES")
            continue
        fam, weight, style, stem = spec
        dest = WEB / "public" / "fonts" / f"{stem}.woff2"
        faces.append(
            f'@font-face {{ font-family: "{fam}"; src: url("/fonts/{stem}.woff2") format("woff2"); '
            f"font-weight: {weight}; font-style: {style}; font-display: swap; }}"
        )
        if dest.exists() or check:
            if check and not dest.exists():
                problems.append(f"missing {dest.relative_to(WEB)}")
            continue
        if not can:
            print(f"warning: {dest.name} missing; pip install fonttools brotli to convert {ttf.name}", file=sys.stderr)
            continue
        f = TTFont(str(ttf))
        f.flavor = "woff2"
        f.save(str(dest))
        print(f"  font {dest.name}")
    return "\n".join(faces), problems


