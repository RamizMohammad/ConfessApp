#!/usr/bin/env python3
"""Generate the web app's design tokens, strings, icons and fonts from the Android app.

The Android res/ folder is the single source of truth for how Confess looks. This script
reads it and writes generated files into the web app, so the two can't drift apart:

  src/android/tokens.css   colours (--c-*), dimensions (--d-*), text styles (.t-*), motion (.m-*)
  src/android/tokens.ts    the same values for code (canvas drawing, inline maths)
  src/android/strings.ts   every <string>, <plurals> and <string-array> (English)
  src/android/icons.ts     every ic_*.xml vector, converted to SVG path data
  src/android/fonts.css    @font-face for every font in res/font
  public/fonts/*.woff2     those fonts, converted from .ttf (needs fonttools + brotli)
  src/android/art.ts       logos, Letty poses and animated vectors (splash, tab icons)
  src/android/*.svg        the splash icon and the launcher icon layers (for scripts/make_app_images.mjs)

Usage:  python3 scripts/android_sync.py [path/to/ConfessMain/app/src/main/res]
        (default: ../ConfessMain/app/src/main/res, or $ANDROID_RES)
        --check   fail if the generated files are out of date (for CI), write nothing

Only the Python standard library is needed, except for fonts (pip install fonttools brotli);
without them the fonts step is skipped with a warning. Generated files say so at the top —
edit the Android XML and re-run, never the output.
"""
