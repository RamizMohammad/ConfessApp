def kebab(name: str) -> str:
    name = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "-", name)
    return name.replace("_", "-").replace(".", "-").lower()


def camel(name: str) -> str:
    parts = re.split(r"[_\-.]", name)
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


# ── colours ──────────────────────────────────────────────────────────────────

def argb_to_css(v: str) -> str:
    h = v.strip().lstrip("#")
    if len(h) == 3:
        h = "".join(c * 2 for c in h)
    if len(h) == 4:
        h = "".join(c * 2 for c in h)
    if len(h) == 6:
        return "#" + h.upper()
    a, r, g, b = int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16), int(h[6:8], 16)
    if a == 255:
        return f"#{h[2:].upper()}"
    return f"rgba({r}, {g}, {b}, {round(a / 255, 3)})"


def read_colors(res: Path) -> dict[str, str]:
    raw: dict[str, str] = {}
    for f in sorted((res / "values").glob("colors*.xml")):
        for el in ET.parse(f).getroot().iter("color"):
            raw[el.get("name")] = (el.text or "").strip()

    def resolve(v: str, depth=0) -> str:
        if v.startswith("@color/") and depth < 10:
            return resolve(raw[v[7:]], depth + 1)
        if v.startswith("@android:color/"):
            return {"transparent": "#00000000", "white": "#FFFFFFFF", "black": "#FF000000"}[v[15:]]
        return v

    return {k: argb_to_css(resolve(v)) for k, v in raw.items()}


# ── dimensions ───────────────────────────────────────────────────────────────

def dim_px(v: str) -> float | None:
    m = re.fullmatch(r"(-?[\d.]+)(dp|dip|sp|px)", v.strip())
    return float(m.group(1)) if m else None


def read_dimens(res: Path) -> dict[str, float]:
    out = {}
    for f in sorted((res / "values").glob("dimens*.xml")):
        for el in ET.parse(f).getroot().iter("dimen"):
            px = dim_px(el.text or "")
            if px is not None:
                out[el.get("name")] = px
    return out


def num(x: float) -> str:
    return str(int(x)) if float(x).is_integer() else f"{x:g}"


# ── text styles ──────────────────────────────────────────────────────────────

def read_type(res: Path) -> dict[str, dict]:
    styles: dict[str, tuple[str | None, dict]] = {}
    for f in sorted((res / "values").glob("type*.xml")):
        for st in ET.parse(f).getroot().iter("style"):
            name = st.get("name")
            parent = st.get("parent")
            if parent is None and "." in name:
                parent = name.rsplit(".", 1)[0]
            props: dict = {}
            for it in st.iter("item"):
                key, val = it.get("name").replace("android:", ""), (it.text or "").strip()
                if key == "fontFamily":
                    props["family"] = val.split("/")[-1]
                elif key == "textSize":
                    props["size"] = dim_px(val)
                elif key == "lineHeight":
                    props["line"] = dim_px(val)
                elif key == "letterSpacing":
                    props["tracking"] = float(val)
                elif key == "textFontWeight":
                    props["weight"] = int(val)
                elif key == "textStyle":
                    props["italic"] = "italic" in val
                elif key == "textAllCaps":
                    props["caps"] = val == "true"
            styles[name] = (parent, props)

    def full(name: str, depth=0) -> dict:
        if name in M3:
            return dict(M3[name])
        if name not in styles or depth > 10:
            return {}
        parent, props = styles[name]
        base = full(parent, depth + 1) if parent else {}
        base.update(props)
        return base

    out = {}
    for name in styles:
        if not name.startswith("TextAppearance.Confess."):
            continue
        short = name[len("TextAppearance.Confess."):]
        p = full(name)
        p.setdefault("weight", 400)
        p.setdefault("italic", False)
        p.setdefault("caps", False)
        p.setdefault("tracking", 0.0)
        out[short] = p
    return out


def type_css(types: dict[str, dict]) -> str:
    rows = []
    for short, p in types.items():
        fam = FAMILY.get(p.get("family", ""), '"Manrope"')
        css = [f"font-family: {fam}, {FALLBACK[fam]}"]
        if p.get("size"):
            css.append(f"font-size: {num(p['size'])}px")
        if p.get("line"):
            css.append(f"line-height: {num(p['line'])}px")
        css.append(f"font-weight: {p['weight']}")
        css.append(f"font-style: {'italic' if p['italic'] else 'normal'}")
        # Android letterSpacing is in ems.
        css.append(f"letter-spacing: {p['tracking']:g}em" if p["tracking"] else "letter-spacing: 0")
        css.append(f"text-transform: {'uppercase' if p['caps'] else 'none'}")
        rows.append(f".t-{kebab(short.replace('.', '-'))} {{ {'; '.join(css)}; }}")
    return "\n".join(rows)


# ── motion ───────────────────────────────────────────────────────────────────

def interp(el, inherited: str) -> str:
    v = el.get(A + "interpolator")
    if not v:
        return inherited
    return EASE.get(v.split("/")[-1], EASE["fast_out_slow_in"])


def pct(v: str | None, default: str) -> str:
    if v is None:
        return default
    v = v.strip()
    if v.endswith("%p"):
        return v[:-2] + "%"
    if v.endswith("%"):
        return v
    return f"{float(v):g}px"


def read_anims(res: Path) -> tuple[str, dict]:
    css, meta = [], {}
    for f in sorted((res / "anim").glob("*.xml")):
        root = ET.parse(f).getroot()
        name = kebab(f.stem)
        if root.tag == "layoutAnimation":
            # A list's first fill: each child plays the item animation, a fraction of it later.
            item = kebab(root.get(A + "animation").split("/")[-1])
            item_ms = int(ET.parse(f.parent / (root.get(A + "animation").split("/")[-1] + ".xml")).getroot().get(A + "duration", "0"))
            frac = float(root.get(A + "delay", "0%").rstrip("%")) / (100 if root.get(A + "delay", "").endswith("%") else 1)
            step = round(item_ms * frac)
            for n in range(1, 21):
                css.append(f".m-{name} > :nth-child({n}) {{ animation: m-{item} var(--m-{item}-ms) var(--m-{item}-ease) {step * (n - 1)}ms both; }}")
            css.append(f".m-{name} > :nth-child(n+21) {{ animation: m-{item} var(--m-{item}-ms) var(--m-{item}-ease) {step * 20}ms both; }}")
            meta[camel(f.stem)] = {"item": camel(item), "stepMs": step}
            continue
        ease = interp(root, EASE["fast_out_slow_in"])
        dur_root = int(root.get(A + "duration", "0") or 0)
        kids = list(root) if root.tag == "set" else [root]
        if root.tag != "set":
            ease = interp(root, ease)
        frm, to, origin = [], [], None
        longest = dur_root
        for k in kids:
            d = int(k.get(A + "duration", dur_root) or dur_root)
            longest = max(longest, d)
            if k.tag == "alpha":
                frm.append(f"opacity: {float(k.get(A + 'fromAlpha', '1')):g}")
                to.append(f"opacity: {float(k.get(A + 'toAlpha', '1')):g}")
            elif k.tag == "translate":
                fx, fy = pct(k.get(A + "fromXDelta"), "0"), pct(k.get(A + "fromYDelta"), "0")
                tx, ty = pct(k.get(A + "toXDelta"), "0"), pct(k.get(A + "toYDelta"), "0")
                frm.append(f"translate: {fx} {fy}")
                to.append(f"translate: {tx} {ty}")
            elif k.tag == "scale":
                frm.append(f"scale: {float(k.get(A + 'fromXScale', '1')):g} {float(k.get(A + 'fromYScale', '1')):g}")
                to.append(f"scale: {float(k.get(A + 'toXScale', '1')):g} {float(k.get(A + 'toYScale', '1')):g}")
                px, py = k.get(A + "pivotX", "50%"), k.get(A + "pivotY", "50%")
                origin = f"{pct(px, '50%')} {pct(py, '50%')}"
        if not frm:
            frm, to = ["opacity: 1"], ["opacity: 1"]
        css.append(f"@keyframes m-{name} {{ from {{ {'; '.join(frm)}; }} to {{ {'; '.join(to)}; }} }}")
        extra = f" transform-origin: {origin};" if origin else ""
        delay = int(root.get(A + "startOffset", "0") or 0)
        css.append(f":root {{ --m-{name}-ms: {longest}ms; --m-{name}-ease: {ease}; }}")
        css.append(f".m-{name} {{ animation: m-{name} {longest}ms {ease} {delay}ms both;{extra} }}")
        meta[camel(f.stem)] = {"ms": longest, "ease": ease, "delayMs": delay}
    css.append("@media (prefers-reduced-motion: reduce) { [class*=\"m-\"] { animation-duration: 1ms !important; } }")
    return "\n".join(css), meta


# ── strings ──────────────────────────────────────────────────────────────────

def clean(s: str) -> str:
    s = s.strip()
    if len(s) >= 2 and s[0] == '"' and s[-1] == '"':
        s = s[1:-1]
    else:
        s = re.sub(r"\s+", " ", s)
    s = s.replace("\\'", "'").replace('\\"', '"').replace("\\n", "\n").replace("\\t", "\t").replace("\\@", "@").replace("\\?", "?")
    return s


def text_of(el) -> str:
    # Inline markup (<b>, <i>, <xliff:g>) is flattened to its text.
    return "".join(el.itertext())


def read_strings(res: Path) -> dict:
    strings, plurals, arrays = {}, {}, {}
    for f in sorted((res / "values").glob("strings*.xml")):
        root = ET.parse(f).getroot()
        for el in root:
            if el.get("translatable") == "false" and el.get("name", "").startswith("google_"):
                continue
            name = el.get("name")
            if el.tag == "string":
                strings[name] = clean(text_of(el))
            elif el.tag == "plurals":
                plurals[name] = {it.get("quantity"): clean(text_of(it)) for it in el.iter("item")}
            elif el.tag in ("string-array", "array"):
                arrays[name] = [clean(text_of(it)) for it in el.iter("item")]
    return {"strings": strings, "plurals": plurals, "arrays": arrays}


# ── icons ────────────────────────────────────────────────────────────────────

def icon_color(v: str | None, colors: dict[str, str]) -> str | None:
    if v is None:
        return None
    if v.startswith("@color/"):
        return f"var(--c-{kebab(v[7:])})"
    if v.startswith("?"):
        return "currentColor"
    css = argb_to_css(v)
    if css in ("rgba(0, 0, 0, 0)",) or v.upper() in ("#00000000", "#0000"):
        return "none"
    return css


def convert_vector(path: Path, colors: dict[str, str]) -> dict | None:
    root = ET.parse(path).getroot()
    if root.tag != "vector":
        return None
    tinted = root.get(A + "tint") is not None
    vw, vh = float(root.get(A + "viewportWidth")), float(root.get(A + "viewportHeight"))
    w, h = dim_px(root.get(A + "width", "24dp")), dim_px(root.get(A + "height", "24dp"))

    def col(v):
        c = icon_color(v, colors)
        # A tinted vector draws white and lets the tint pick the colour: that's currentColor.
        if tinted and c in ("#FFFFFF",):
            return "currentColor"
        return c

    def walk(el) -> list:
        out = []
        for k in el:
            tag = k.tag
            if tag == "path":
                d = {"d": k.get(A + "pathData")}
                fill, stroke = col(k.get(A + "fillColor")), col(k.get(A + "strokeColor"))
                d["fill"] = fill or "none"
                if stroke and stroke != "none":
                    d["stroke"] = stroke
                    d["sw"] = float(k.get(A + "strokeWidth", "0") or 0)
                    if k.get(A + "strokeLineCap"):
                        d["cap"] = k.get(A + "strokeLineCap")
                    if k.get(A + "strokeLineJoin"):
                        d["join"] = k.get(A + "strokeLineJoin")
                for a, key in (("fillAlpha", "fo"), ("strokeAlpha", "so")):
                    if k.get(A + a):
                        d[key] = float(k.get(A + a))
                if k.get(A + "fillType") == "evenOdd":
                    d["rule"] = "evenodd"
                out.append(d)
            elif tag == "group":
                tx, ty = float(k.get(A + "translateX", 0)), float(k.get(A + "translateY", 0))
                sx, sy = float(k.get(A + "scaleX", 1)), float(k.get(A + "scaleY", 1))
                rot = float(k.get(A + "rotation", 0))
                px, py = float(k.get(A + "pivotX", 0)), float(k.get(A + "pivotY", 0))
                # Android order: translate(pivot+translate) rotate scale translate(-pivot).
                t = []
                if tx or ty or px or py:
                    t.append(f"translate({num(tx + px)} {num(ty + py)})")
                if rot:
                    t.append(f"rotate({num(rot)})")
                if sx != 1 or sy != 1:
                    t.append(f"scale({num(sx)} {num(sy)})")
                if px or py:
                    t.append(f"translate({num(-px)} {num(-py)})")
                out.append({"g": " ".join(t), "c": walk(k)})
            elif tag == "clip-path":
                out.append({"clip": k.get(A + "pathData")})
        return out

    return {"vb": f"0 0 {num(vw)} {num(vh)}", "w": w, "h": h, "tinted": tinted, "c": walk(root)}


def read_icons(res: Path, colors: dict[str, str]) -> dict:
    out = {}
    for f in sorted((res / "drawable").glob("ic_*.xml")):
        try:
            v = convert_vector(f, colors)
        except ET.ParseError:
            v = None
        if v:
            out[f.stem[3:]] = v
    return out


AAPT = "{http://schemas.android.com/aapt}"


def vector_svg(path: Path) -> str:
    """A whole VectorDrawable as standalone SVG markup (with aapt gradients) — for the splash."""
    root = ET.parse(path).getroot()
    vw, vh = root.get(A + "viewportWidth"), root.get(A + "viewportHeight")
    w, h = dim_px(root.get(A + "width")), dim_px(root.get(A + "height"))
    defs: list[str] = []

    def paint(el, attr: str) -> str | None:
        for a in el.findall(AAPT + "attr"):
            if a.get("name") == "android:" + attr:
                g = a.find("gradient")
                gid = f"g{len(defs)}"
                stops = "".join(
                    f'<stop offset="{float(it.get(A + "offset")):g}" stop-color="{argb_to_css(it.get(A + "color"))}"/>'
                    for it in g.findall("item"))
                kind = g.get(A + "type", "linear")
                if kind == "radial":
                    defs.append(f'<radialGradient id="{gid}" gradientUnits="userSpaceOnUse" cx="{g.get(A + "centerX")}" '
                                f'cy="{g.get(A + "centerY")}" r="{g.get(A + "gradientRadius")}">{stops}</radialGradient>')
                else:
                    defs.append(f'<linearGradient id="{gid}" gradientUnits="userSpaceOnUse" x1="{g.get(A + "startX")}" '
                                f'y1="{g.get(A + "startY")}" x2="{g.get(A + "endX")}" y2="{g.get(A + "endY")}">{stops}</linearGradient>')
                return f"url(#{gid})"
        v = el.get(A + attr)
        if v is None:
            return None
        if v.startswith("@color/"):
            return argb_to_css(COLORS[v[7:]]) if not COLORS[v[7:]].startswith(("#", "rgba")) else COLORS[v[7:]]
        return argb_to_css(v)

    def walk(el) -> str:
        out = []
        for k in el:
            if k.tag == "path":
                a = [f'd="{path_data(k.get(A + "pathData"))}"', f'fill="{paint(k, "fillColor") or "none"}"']
                st = paint(k, "strokeColor")
                if st:
                    a += [f'stroke="{st}"', f'stroke-width="{k.get(A + "strokeWidth", "0")}"']
                    if k.get(A + "strokeLineCap"):
                        a.append(f'stroke-linecap="{k.get(A + "strokeLineCap")}"')
                    if k.get(A + "strokeLineJoin"):
                        a.append(f'stroke-linejoin="{k.get(A + "strokeLineJoin")}"')
                if k.get(A + "fillAlpha"):
                    a.append(f'fill-opacity="{k.get(A + "fillAlpha")}"')
                if k.get(A + "strokeAlpha"):
                    a.append(f'stroke-opacity="{k.get(A + "strokeAlpha")}"')
                if k.get(A + "fillType") == "evenOdd":
                    a.append('fill-rule="evenodd"')
                out.append(f"<path {' '.join(a)}/>")
            elif k.tag == "group":
                tx, ty = float(k.get(A + "translateX", 0)), float(k.get(A + "translateY", 0))
                sx, sy = float(k.get(A + "scaleX", 1)), float(k.get(A + "scaleY", 1))
                rot = float(k.get(A + "rotation", 0))
                px, py = float(k.get(A + "pivotX", 0)), float(k.get(A + "pivotY", 0))
                t = f"translate({num(tx + px)} {num(ty + py)}) rotate({num(rot)}) scale({num(sx)} {num(sy)}) translate({num(-px)} {num(-py)})"
                out.append(f'<g transform="{t}">{walk(k)}</g>')
        return "".join(out)

    body = walk(root)
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{num(w)}" height="{num(h)}" viewBox="0 0 {vw} {vh}">'
            f'<defs>{"".join(defs)}</defs>{body}</svg>\n')


COLORS: dict[str, str] = {}


# ── art: logos, Letty poses, animated vectors ──────────────────────────────────

PATH_STRINGS: dict[str, str] = {}


def path_data(v: str | None) -> str | None:
    if v and v.startswith("@string/"):
        return PATH_STRINGS.get(v[8:], "")
    return v


def art_vector(root, tinted_default=False) -> dict:
    """A VectorDrawable as node data the web can draw and animate (names, raw group props, gradients)."""
    tinted = root.get(A + "tint") is not None or tinted_default
    vw, vh = root.get(A + "viewportWidth"), root.get(A + "viewportHeight")
    w, h = dim_px(root.get(A + "width", "24dp")), dim_px(root.get(A + "height", "24dp"))
    defs: list[dict] = []

    def paint(el, attr: str):
        for a in el.findall(AAPT + "attr"):
            if a.get("name") == "android:" + attr:
                g = a.find("gradient")
                stops = [[float(it.get(A + "offset")), argb_to_css(it.get(A + "color"))] for it in g.findall("item")]
                if not stops:
                    stops = [[0, argb_to_css(g.get(A + "startColor"))], [1, argb_to_css(g.get(A + "endColor"))]]
                gd = {"id": f"g{len(defs)}", "type": g.get(A + "type", "linear"), "stops": stops}
                for k in ("centerX", "centerY", "gradientRadius", "startX", "startY", "endX", "endY"):
                    if g.get(A + k) is not None:
                        gd[k] = float(g.get(A + k))
                defs.append(gd)
                return {"grad": gd["id"]}
        v = el.get(A + attr)
        if v is None:
            return None
        if v.startswith("@color/"):
            return f"var(--c-{kebab(v[7:])})"
        if v.startswith("?"):
            return "currentColor"
        if v.upper() in ("#00000000", "#0000"):
            return "none"
        css = argb_to_css(v)
        if tinted and css == "#FFFFFF":
            return "currentColor"
        return css

    def walk(el) -> list:
        out = []
        for k in el:
            if k.tag == "path":
                n = {"t": "p", "d": path_data(k.get(A + "pathData"))}
                if k.get(A + "name"):
                    n["n"] = k.get(A + "name")
                f, st = paint(k, "fillColor"), paint(k, "strokeColor")
                n["f"] = f if f is not None else "none"
                if st is not None and st != "none":
                    n["s"] = st
                    n["sw"] = float(k.get(A + "strokeWidth", "0") or 0)
                    for a, key in (("strokeLineCap", "cap"), ("strokeLineJoin", "join")):
                        if k.get(A + a):
                            n[key] = k.get(A + a)
                for a, key in (("fillAlpha", "fa"), ("strokeAlpha", "sa"), ("trimPathStart", "ts"),
                               ("trimPathEnd", "te"), ("trimPathOffset", "to")):
                    if k.get(A + a) is not None:
                        n[key] = float(k.get(A + a))
                if k.get(A + "fillType") == "evenOdd":
                    n["rule"] = "evenodd"
                out.append(n)
            elif k.tag == "group":
                n = {"t": "g", "c": walk(k)}
                if k.get(A + "name"):
                    n["n"] = k.get(A + "name")
                for a, key, dflt in (("translateX", "tx", 0), ("translateY", "ty", 0), ("scaleX", "sx", 1),
                                     ("scaleY", "sy", 1), ("rotation", "r", 0), ("pivotX", "px", 0), ("pivotY", "py", 0)):
                    v = float(k.get(A + a, dflt))
                    if v != dflt:
                        n[key] = v
                out.append(n)
            elif k.tag == "clip-path":
                out.append({"t": "c", "d": path_data(k.get(A + "pathData"))})
        return out

    data = {"vb": f"0 0 {vw} {vh}", "w": w, "h": h, "c": walk(root)}
    if defs:
        data["defs"] = defs
    if tinted:
        data["tinted"] = True
    return data


INTERPOLATORS = {
    "accelerate_decelerate_interpolator": "accelerate_decelerate", "accelerate_decelerate": "accelerate_decelerate",
    "decelerate_quad": "decelerate_quad", "decelerate_interpolator": "decelerate_quad",
    "accelerate_quad": "accelerate_quad", "accelerate_interpolator": "accelerate_quad",
    "overshoot_interpolator": "overshoot", "fast_out_slow_in": "fast_out_slow_in", "linear": "linear",
    "linear_interpolator": "linear", "decelerate_cubic": "decelerate_cubic", "accelerate_cubic": "accelerate_cubic",
}


def read_art(res: Path) -> dict:
    out: dict = {"vectors": {}, "anims": {}}
    for f in sorted((res / "drawable").glob("*.xml")):
        if f.stem.startswith("ic_"):
            continue
        try:
            root = ET.parse(f).getroot()
        except ET.ParseError:
            continue
        if root.tag == "vector":
            out["vectors"][f.stem] = art_vector(root)
        elif root.tag == "animated-vector":
            drawable = root.get(A + "drawable")
            avd = {}
            if drawable:
                avd["drawable"] = drawable.split("/")[-1]
            else:
                inline = next((a for a in root.findall(AAPT + "attr") if a.get("name") == "android:drawable"), None)
                if inline is not None:
                    name = f.stem + "__vector"
                    out["vectors"][name] = art_vector(inline.find("vector"), tinted_default=True)
                    avd["drawable"] = name
            targets = {}
            for t in root.findall("target"):
                anims = []
                holder = next((a for a in t.findall(AAPT + "attr") if a.get("name") == "android:animation"), None)
                if holder is None:
                    continue
                for oa in holder.iter("objectAnimator"):
                    ip = (oa.get(A + "interpolator") or "accelerate_decelerate").split("/")[-1]
                    anims.append({
                        "p": oa.get(A + "propertyName"), "from": float(oa.get(A + "valueFrom", "0")),
                        "to": float(oa.get(A + "valueTo", "0")), "at": int(oa.get(A + "startOffset", "0")),
                        "ms": int(oa.get(A + "duration", "300")), "ease": INTERPOLATORS.get(ip, "accelerate_decelerate"),
                    })
                targets[t.get(A + "name")] = anims
            avd["targets"] = targets
            avd["ms"] = max((a["at"] + a["ms"] for v in targets.values() for a in v), default=0)
            out["anims"][f.stem] = avd
    return out


